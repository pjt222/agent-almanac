#!/usr/bin/env bash
# capture.sh — regenerate probe-runs.txt for the rm-audit result directory.
#
# Every section prints the LITERAL command line that produced it, so a re-deriver runs what was
# run rather than guessing. Session identifiers in the output are replaced with the same
# placeholder shape this PR's first commit used, since the raw paths carry session ids and add
# nothing a reader can act on.
set -uo pipefail

REPO=/mnt/d/dev/p/agent-almanac
D="$REPO/tests/results/2026-09-17-repo-safety-rm-audit"
OUT="$D/probe-runs.txt"

# The root list, derived rather than typed. Printed so it can be re-run verbatim.
ROOTS_CMD='ls -1d ~/.claude/projects/-mnt-d-dev-p-agent-almanac/*/subagents'
# shellcheck disable=SC2086
ROOTS=$(eval "$ROOTS_CMD")

scrub() {
  sed -E \
    -e 's#/home/[a-z]+/#/home/<user>/#g' \
    -e 's#/tmp/claude-[0-9]+/#/tmp/claude-<uid>/#g' \
    -e 's#[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}#<session-id>#g'
}

{
  echo "# probe-runs.txt — regenerated by capture.sh beside this file."
  echo "# Session ids and home paths are placeholdered; counts and commands are verbatim."
  echo
  echo "ROOTS were derived with:"
  echo "    $ROOTS_CMD"
  echo "and resolved to $(echo "$ROOTS" | wc -l) directory/ies."
  echo

  echo "=== corpus digest — the name this run's figures belong to ==="
  echo "# Content-only, order-independent, and it publishes no path and no identifier."
  echo "# A re-deriver whose digest differs has a different corpus and numbers that are not"
  echo "# comparable to these — which is the failure the drift across five review rounds shows."
  echo "# COUNT FIRST, then hash. Over zero files this pipeline returns"
  echo "#   38acb15d02d5ac0f2a2789602e9df950c380d2799b4bdb59394e4eeabdd3a662"
  echo "# — the sha256 of an empty list of hashes, a universal constant. 64 confident hex"
  echo "# characters and no refusal is exactly the vacuous pass this whole result file is about,"
  echo "# so the count gates the digest rather than trailing it."
  echo "\$ n=\$(find <roots> -name '*.jsonl' -type f | wc -l)"
  echo "\$ [ \"\$n\" -gt 0 ] || { echo 'REFUSED: no files' >&2; exit 2; }"
  echo "\$ find <roots> -name '*.jsonl' -type f -print0 | sort -z | xargs -0 sha256sum \\"
  echo "    | awk '{print \$1}' | sort | sha256sum"
  # shellcheck disable=SC2086
  DIGEST_N=$(find $ROOTS -name '*.jsonl' -type f 2>/dev/null | wc -l)
  if [ "$DIGEST_N" -eq 0 ]; then
    echo "  REFUSED: the root expansion matched no .jsonl — a digest over nothing is a constant"
  else
    echo "  over $DIGEST_N file(s)"
    # shellcheck disable=SC2086
    find $ROOTS -name '*.jsonl' -type f -print0 2>/dev/null | sort -z | xargs -0 sha256sum |
      awk '{print $1}' | sort | sha256sum | awk '{print "  digest: " $1}'
  fi
  echo

  echo "=== disk denominator: non-recursive vs recursive ==="
  echo "\$ ls -1 ~/.claude/projects/-mnt-d-dev-p-agent-almanac/*/subagents/*.jsonl | wc -l"
  ls -1 ~/.claude/projects/-mnt-d-dev-p-agent-almanac/*/subagents/*.jsonl 2>/dev/null | wc -l
  echo "\$ find <roots> -name '*.jsonl' -type f | wc -l"
  # shellcheck disable=SC2086
  find $ROOTS -name '*.jsonl' -type f 2>/dev/null | wc -l
  echo "\$ depth below subagents/ (0 = direct child)"
  # shellcheck disable=SC2086
  find $ROOTS -name '*.jsonl' -type f -printf '%h\n' 2>/dev/null |
    sed 's|.*/subagents||' | awk -F/ '{print NF-1}' | sort | uniq -c
  echo

  echo "=== node rm-audit.mjs <roots> --rows ==="
  # shellcheck disable=SC2086
  node "$D/rm-audit.mjs" $ROOTS --rows
  echo

  echo "=== node rm-audit.mjs <roots> --since 2026-09-16 --until 2026-09-16 ==="
  echo "    (the window commit c6addaea3's own figures describe)"
  # shellcheck disable=SC2086
  node "$D/rm-audit.mjs" $ROOTS --since 2026-09-16 --until 2026-09-16 | head -18
  echo

  echo "=== node rm-count-variants.mjs <roots> ==="
  # shellcheck disable=SC2086
  node "$D/rm-count-variants.mjs" $ROOTS
  echo

  echo "=== node render-check.mjs --self-test ==="
  node "$D/render-check.mjs" --self-test
  echo "exit=$?"
  echo

  echo "=== negative arm: a root holding no .jsonl ==="
  echo "\$ node rm-audit.mjs /tmp"
  node "$D/rm-audit.mjs" /tmp 2>&1
  echo "exit=$?"
} 2>&1 | scrub > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
