/**
 * vibe.js — Mistral Vibe adapter.
 *
 * Skills: .vibe/skills/<id>/ (project) or ~/.vibe/skills/<id>/ (global)
 * Agents: ~/.vibe/agents/<id>.toml (global only)
 */

import { existsSync, readdirSync } from 'fs';
import { resolve } from 'path';
import { homedir } from 'os';
import { FrameworkAdapter, childPath } from './base.js';
import { describeEntry, installAt, isInternalName, placeGenerated, removeEntry, removeGenerated } from '../lib/placement.js';

export class VibeAdapter extends FrameworkAdapter {
  static id = 'vibe';
  static displayName = 'Mistral Vibe';
  static strategy = 'symlink';
  static contentTypes = ['skill', 'agent'];
  /** @type {Record<string, string[]>} #607: _skillsBase() branches on scope; _agentsBase() takes no scope and is always ~/.vibe/agents. */
  static scopes = { skill: ['project', 'global'], agent: ['global'] };

  async detect(projectDir) {
    return existsSync(resolve(projectDir, '.vibe'));
  }

  _skillsBase(projectDir, scope) {
    return scope === 'global'
      ? resolve(homedir(), '.vibe/skills')
      : resolve(projectDir, '.vibe/skills');
  }

  _agentsBase() {
    return resolve(homedir(), '.vibe/agents');
  }

  /**
   * The agent's TOML. Byte for byte the template agent-almanac 1.9.1 wrote,
   * so an unmarked file from it is recognised (#998, back-compat (b)) while
   * the item's description, tools and source path are what they were then.
   */
  _agentToml(item) {
    const description = item.description || item.id;
    const tools = (item.tools || []).map(t => `"${t}"`).join(', ');
    return `# Agent: ${item.id}
# Generated by agent-almanac CLI
# Source: ${item.sourcePath || 'unknown'}

[agent]
name = "${item.id}"
description = "${description}"
tools = [${tools}]

[agent.prompt]
system_prompt_id = "${item.id}"
`;
  }

  async install(item, projectDir, scope, options = {}) {
    if (item.type === 'skill') {
      const targetBase = this._skillsBase(projectDir, scope);
      const targetPath = childPath(targetBase, item.id);
      if (options.dryRun) return { action: 'created', path: targetPath, details: 'dry-run' };
      return installAt({
        base: targetBase, name: item.id, item, options, relativeLink: scope !== 'global',
        source: item.sourceDir || resolve(options.almanacRoot, 'skills', item.id),
      });
    }

    if (item.type === 'agent') {
      // Vibe uses .toml files for agents: a generated minimal config, with a
      // sidecar marker, so uninstall and --force touch only the CLI's own (#998).
      const agentsDir = this._agentsBase();
      const name = `${item.id}.toml`;
      const targetPath = childPath(agentsDir, name);
      if (options.dryRun) return { action: 'created', path: targetPath, details: 'dry-run' };
      return placeGenerated({
        base: agentsDir, name, item, options, content: this._agentToml(item),
        source: item.sourcePath || resolve(options.almanacRoot, 'agents', `${item.id}.md`),
      });
    }

    return { action: 'skipped', path: '', details: `${item.type}s not supported` };
  }

  async uninstall(item, projectDir, scope, options = {}) {
    if (item.type === 'skill') {
      return removeEntry(this._skillsBase(projectDir, scope), item.id, { dryRun: options.dryRun });
    }

    if (item.type === 'agent') {
      return removeGenerated(this._agentsBase(), `${item.id}.toml`, { dryRun: options.dryRun, content: this._agentToml(item) });
    }

    return { action: 'skipped', path: '', details: `${item.type}s not supported` };
  }

  async listInstalled(projectDir, scope) {
    const items = [];
    const skillsDir = this._skillsBase(projectDir, scope);
    if (existsSync(skillsDir)) {
      for (const name of readdirSync(skillsDir)) {
        if (isInternalName(name)) continue;
        const fullPath = resolve(skillsDir, name);
        items.push({ id: name, type: 'skill', path: fullPath, ...describeEntry(fullPath).fields });
      }
    }
    const agentsDir = this._agentsBase();
    if (existsSync(agentsDir)) {
      for (const name of readdirSync(agentsDir)) {
        if (name.endsWith('.toml')) {
          // Agent .toml files are generated in place, not linked — they cannot dangle.
          items.push({ id: name.replace(/\.toml$/, ''), type: 'agent', path: resolve(agentsDir, name), broken: false });
        }
      }
    }
    return items;
  }

  async audit(projectDir, scope, listed) {
    const installed = listed ?? await this.listInstalled(projectDir, scope);
    // Only skills are symlinked; agent .toml files are generated in place and
    // are flagged broken:false, so they can never be counted here.
    const broken = installed.filter(i => i.broken);
    const valid = installed.filter(i => !i.broken);
    return {
      framework: VibeAdapter.displayName,
      ok: valid.length > 0 ? [`${valid.length} items installed`] : [],
      warnings: installed.length === 0 ? ['No Vibe content installed'] : [],
      errors: broken.length > 0 ? [`${broken.length} broken skill symlinks`] : [],
    };
  }
}
